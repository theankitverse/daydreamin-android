package com.daydreamin.app.data.remote

import android.os.Build
import okhttp3.OkHttpClient
import java.security.KeyStore
import java.security.cert.CertificateFactory
import java.security.cert.X509Certificate
import javax.net.ssl.SSLContext
import javax.net.ssl.TrustManagerFactory
import javax.net.ssl.X509TrustManager

/**
 * Android 7.0 and older ship without the root certificates several of our servers now chain to —
 * GitHub (the update check), Apple (charts, artwork) and Let's Encrypt sites — so on those phones
 * every such request fails its TLS handshake. There, the system's roots plus these four are
 * trusted; nothing is skipped or loosened, and on Android 7.1.1+ clients are left untouched.
 */
object LegacyTls {
    private val needed = Build.VERSION.SDK_INT < Build.VERSION_CODES.N_MR1

    private val trustManager: X509TrustManager? by lazy {
        if (!needed) return@lazy null
        runCatching {
            val store = KeyStore.getInstance(KeyStore.getDefaultType()).apply { load(null, null) }
            val system = KeyStore.getInstance("AndroidCAStore").apply { load(null, null) }
            system.aliases().toList().forEach { alias -> store.setCertificateEntry(alias, system.getCertificate(alias)) }
            // One certificate at a time, each trimmed: Android's parser sniffs the first byte for
            // the format, and a bundle read in one go (or with a leading newline) parsed as nothing.
            val factory509 = CertificateFactory.getInstance("X.509")
            ROOTS.split("-----END CERTIFICATE-----").map { it.trim() }.filter { it.isNotEmpty() }.forEachIndexed { i, pem ->
                val cert = factory509.generateCertificate("$pem\n-----END CERTIFICATE-----\n".byteInputStream()) as X509Certificate
                store.setCertificateEntry("daydreamin-root-$i", cert)
            }
            val factory = TrustManagerFactory.getInstance(TrustManagerFactory.getDefaultAlgorithm()).apply { init(store) }
            factory.trustManagers.filterIsInstance<X509TrustManager>().first()
        }.onFailure { android.util.Log.w("LegacyTls", "couldn't add the bundled roots", it) }.getOrNull()
    }

    /** Trusts the bundled roots too, on the Android versions that lack them. */
    fun OkHttpClient.Builder.withLegacyRoots(): OkHttpClient.Builder = apply {
        val tm = trustManager ?: return@apply
        val context = SSLContext.getInstance("TLS").apply { init(null, arrayOf(tm), null) }
        sslSocketFactory(context.socketFactory, tm)
    }

    val isNeeded: Boolean get() = needed

